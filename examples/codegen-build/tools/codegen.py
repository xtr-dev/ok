#!/usr/bin/env python3
"""Turn every JSON schema in a directory into a Rust struct (part of the Makefile build)."""
import json
import pathlib
import sys

TYPES = {"string": "String", "integer": "i64", "number": "f64", "boolean": "bool"}


def field(name, prop, required):
    try:
        base = TYPES[prop["type"]]
    except KeyError:
        sys.exit(f"unsupported schema type {prop.get('type')} for field {name}")
    ty = base if required else f"Option<{base}>"
    return f"    pub {name}: {ty},"


def rust_struct(schema):
    required = set(schema.get("required", []))
    fields = [field(k, v, k in required) for k, v in schema["properties"].items()]
    return (
        "#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]\n"
        f"pub struct {schema['title']} {{\n" + "\n".join(fields) + "\n}\n"
    )


out = ["// Generated by `make`. Do not edit.\n"]
for path in sorted(pathlib.Path(sys.argv[1]).glob("*.json")):
    out.append(rust_struct(json.loads(path.read_text())))
print("\n".join(out), end="")
